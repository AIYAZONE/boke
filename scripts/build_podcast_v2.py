def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError("CMD FAILED: %s\n%s" % (" ".join(cmd), r.stderr[-1500:]))
    return r.stdout


def silence(path, dur):
    run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono",
         "-t", str(dur), "-c:a", "libmp3lame", "-b:a", "64k", "-ar", "24000", "-ac", "1", path])


def make_intro(path):
    t1 = os.path.join(TMP, "_t1.mp3")
    t2 = os.path.join(TMP, "_t2.mp3")
    run(["ffmpeg", "-y", "-f", "lavfi", "-i", "sine=frequency=523.25:sample_rate=24000:duration=0.36",
         "-c:a", "libmp3lame", "-b:a", "64k", "-ar", "24000", "-ac", "1", t1])
    run(["ffmpeg", "-y", "-f", "lavfi", "-i", "sine=frequency=659.25:sample_rate=24000:duration=0.55",
         "-c:a", "libmp3lame", "-b:a", "64k", "-ar", "24000", "-ac", "1", t2])
    run(["ffmpeg", "-y", "-i", t1, "-i", t2, "-filter_complex",
         "[0:a]afade=t=in:st=0:d=0.02,afade=t=out:st=0.24:d=0.12,volume=0.18[a];"
         "[1:a]afade=t=in:st=0:d=0.02,afade=t=out:st=0.38:d=0.17,volume=0.18[b];"
         "[a][b]concat=n=2:v=0:a=1[out]",
         "-map", "[out]", "-c:a", "libmp3lame", "-b:a", "64k", "-ar", "24000", "-ac", "1", path])


def concat(parts, out):
    lst = os.path.join(TMP, "_list_%s.txt" % os.path.basename(out).replace(".mp3", ""))
    with open(lst, "w") as f:
        for p in parts:
            f.write("file '%s'\n" % p)
    run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", lst,
         "-af", "aresample=24000", "-c:a", "libmp3lame", "-b:a", "64k",
         "-ar", "24000", "-ac", "1", out])


def duration(path):
    return float(run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                      "-of", "default=noprint_wrappers=1:nokey=1", path]).strip())


async def main():
    silence(os.path.join(TMP, "_sil.mp3"), 0.30)
    silence(os.path.join(TMP, "_sil_long.mp3"), 0.75)
    make_intro(os.path.join(TMP, "_intro.mp3"))
    sil = os.path.join(TMP, "_sil.mp3")
    sil_long = os.path.join(TMP, "_sil_long.mp3")
    intro = os.path.join(TMP, "_intro.mp3")

    sem = asyncio.Semaphore(5)

    async def one(text, spk, path):
        async with sem:
            voice, rate = VOICES[spk]
            for attempt in range(3):
                try:
                    await edge_tts.Communicate(text, voice, rate=rate).save(path)
                    if os.path.getsize(path) > 1000:
                        return
                except Exception as e:
                    print("retry", path, e, flush=True)
                    await asyncio.sleep(1.5)
            raise RuntimeError("TTS failed: " + path)

    tasks = []
    for ep in EPISODES:
        for i, (spk, text) in enumerate(ep["segments"]):
            p = os.path.join(TMP, "%s_%03d.mp3" % (ep["id"], i))
            tasks.append(one(text, spk, p))
    print("total segments:", len(tasks), flush=True)
    await asyncio.gather(*tasks)
    print("TTS done", flush=True)

    meta = []
    for ep in EPISODES:
        parts = [intro, sil]
        for i in range(len(ep["segments"])):
            parts.append(os.path.join(TMP, "%s_%03d.mp3" % (ep["id"], i)))
            parts.append(sil)
        out = os.path.join(OUT, ep["file"])
        concat(parts, out)
        d = duration(out)
        meta.append({
            "id": ep["id"], "file": "podcast/" + ep["file"], "title": ep["title"],
            "subtitle": ep["subtitle"], "notes": ep["notes"],
            "duration": round(d, 1), "chars": sum(len(t) for _, t in ep["segments"]),
            "turns": len(ep["segments"]),
        })
        print(ep["id"], "%.1fs" % d, flush=True)

    full = os.path.join(OUT, "YC20_full.mp3")
    fp = []
    for m in meta:
        fp.append(os.path.join(BASE, m["file"]))
        fp.append(sil_long)
    concat(fp, full)
    full_d = duration(full)
    print("FULL %.1fs" % full_d, flush=True)

    with open("/root/.codebuddy/artifact/2f8a7d30-9c21-4f0b-1d6d-135415108000/podcast_meta_v2.json", "w") as f:
        json.dump({"episodes": meta, "full": {"file": "podcast/YC20_full.mp3", "duration": round(full_d, 1)}},
                  f, ensure_ascii=False, indent=2)

    # ---- 逐字稿 + Show Notes（文案去 AI 味）----
